// 강조 막대를 포커스가 들어간 항목 자리로 옮긴다. 하이라이트 판정은 Radix가 item.focus()로 하고 여기선 자리만 읽는다
function trackHighlight(bar: HTMLSpanElement | null) {
  const content = bar?.closest<HTMLElement>("[data-slot=select-content]")
  if (!bar || !content) return
  const onFocus = (e: FocusEvent) => {
    const item = e.target instanceof HTMLElement ? e.target.closest<HTMLElement>("[data-slot=select-item]") : null
    if (!item) {
      bar.removeAttribute("data-on")
      return
    }
    // 처음 나타날 때는 위에서 미끄러져 오지 않게 전환 없이 자리를 잡는다
    const first = !bar.hasAttribute("data-on")
    if (first) bar.style.transition = "none"
    bar.style.transform = `translate(${item.offsetLeft}px, ${item.offsetTop}px)`
    bar.style.width = `${item.offsetWidth}px`
    bar.style.height = `${item.offsetHeight}px`
    bar.setAttribute("data-on", "")
    if (first) {
      void bar.offsetWidth
      bar.style.transition = ""
    }
  }
  content.addEventListener("focusin", onFocus)
  return () => content.removeEventListener("focusin", onFocus)
}

function SelectContent({
  className,
  children,
  position = "item-aligned",
  align = "center",
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        data-align-trigger={position === "item-aligned"}
        className={cn("u031-list relative z-50 max-h-(--radix-select-content-available-height) min-w-36 overflow-x-hidden overflow-y-auto", position ==="popper"&&"data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1", className )}
        position={position}
        align={align}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          data-position={position}
          className={cn(
            "u031-vp data-[position=popper]:h-(--radix-select-trigger-height) data-[position=popper]:w-full data-[position=popper]:min-w-(--radix-select-trigger-width)",
            position === "popper" && ""
          )}
        >
          <span ref={trackHighlight} className="u031-hl" aria-hidden />
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

